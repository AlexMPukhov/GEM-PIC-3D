const Element* findElement(const std::string& symbol) {
  std::string s = symbol;
  for (auto& ch : s) ch = char(std::tolower(static_cast<unsigned char>(ch)));
  for (const auto& e : elements()) {
    std::string t = e.symbol;
    for (auto& ch : t) ch = char(std::tolower(static_cast<unsigned char>(ch)));
    if (s == t) return &e;
  }
  return nullptr;
}

const char* atomicDataSource() {
  return "NIST Atomic Spectra Database ver. 5.12 (Kramida, Ralchenko, Reader and NIST ASD Team, 2024), "
         "ionization energies retrieved 2026-09-27";
}

