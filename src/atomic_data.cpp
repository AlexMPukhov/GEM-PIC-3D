// ============================================================================
//  atomic_data.cpp -- (ported from GEM-PIC-RZ) ionization energies from the NIST Atomic Spectra Database
//
//  Source: A. Kramida, Yu. Ralchenko, J. Reader and NIST ASD Team (2024),
//  NIST Atomic Spectra Database (ver. 5.12), "Ground levels and ionization
//  energies", https://physics.nist.gov/asd, retrieved 2026-09-27 with the query
//    https://physics.nist.gov/cgi-bin/ASD/ie.pl?spectra=<El>&units=1&format=1
//  (units: eV). Row k is the energy needed to remove one electron from the
//  ion with charge +k (ground state), i.e. the potential of the level that is
//  ionized in the transition k -> k+1.
//
//  NIST marks some values of highly charged ions as theoretical ([...]) or as
//  interpolated / semi-empirical ((...)); these are used as they are. This
//  concerns in particular Cu (k = 3..9, 11..28) and Kr (k = 4..6, 8..35); for
//  Ag, Xe and Au the retrieved table did not show the markers, so the deep
//  levels of these elements should also be treated as less certain.
//
//  Deuterium uses the hydrogen value (the isotope shift is ~4 meV).
//  Standard atomic masses: IUPAC.
// ============================================================================
